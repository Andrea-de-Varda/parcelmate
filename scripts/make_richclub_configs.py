"""Write the configs of the rich-club stage (LOG.md Iteration 45, info/RICH_CLUB_PLAN.md).

    python scripts/make_richclub_configs.py

The pooled residual connectome of Iteration 43, recomputed and KEPT (`purge_connectivity:
false`) in its own tree under results/richclub/, because every Qwen run purged its tiles
after scoring and the network-neuroscience stages need the connectome itself.

  qwen3.5-{2b,4b}-resid-pool4-tiles  the connectivity block of configs/qwen35/qwen3.5-*-resid-
                                     pool4.yml unchanged (same seed, documents, residual fit),
                                     so the tiles are those the circuit networks were fitted
                                     on. The stored partitions are copied in, not refitted;
                                     re-scoring them on the new tiles must reproduce the
                                     stored scores (scripts/check_tiles_reproduce.py).
  pythia-70m-resid-pool4-tiles       the pilot: the same design on Pythia-70m (final
                                     checkpoint), whose residual runs were single-dataset.
                                     Full pipeline (connectivity, parcellation, score).

The `-tiles` suffix keeps the job names apart from the original runs' jobs.

  <model>-resid-pool4-docs           (Iteration 48) the same three connectomes on document-
                                     coherent text (`data_kwargs: {sampling: documents}`):
                                     wikitext and bookcorpus as windows of contiguous text,
                                     agnews and tldr17 packed with the end-of-text token between
                                     documents. Full pipeline for every model, tiles kept: one
                                     tree serves both the circuit comparison and the rich club.
"""

import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from make_qwen_configs import MODELS, config  # noqa: E402

OUT = os.path.join(HERE, '..', 'configs', 'richclub')

SPECS = {
    'qwen3.5-2b-resid-pool4-tiles': dict(MODELS['qwen3.5-2b-resid-pool4'], source='qwen3.5-2b-resid-pool4'),
    'qwen3.5-4b-resid-pool4-tiles': dict(MODELS['qwen3.5-4b-resid-pool4'], source='qwen3.5-4b-resid-pool4'),
    'pythia-70m-resid-pool4-tiles': dict(model='EleutherAI/pythia-70m', revision='step143000', layers=6,
                                         neurons=2048, pool_as='pooled', resid=True, pool_tokens=102400,
                                         domains=['wikitext', 'bookcorpus', 'agnews', 'tldr17']),
}
for _m in ('qwen3.5-2b', 'qwen3.5-4b', 'pythia-70m'):
    _base = {k: v for k, v in SPECS['%s-resid-pool4-tiles' % _m].items() if k != 'source'}
    SPECS['%s-resid-pool4-docs' % _m] = dict(_base, docs=True)

HEADER = """# Rich-club stage (LOG.md Iteration 45, info/RICH_CLUB_PLAN.md): %(model)s, all %(units)d MLP
# neurons, the POOLED RESIDUAL connectome of Iteration 43 (four prose datasets; half A = sample 1
# of each, half B = sample 2; each half the Fisher mean over its four samples). Generated by
# scripts/make_richclub_configs.py; edit that script, not this file.
#
# The tiles are KEPT (%(gb).1f GB per half, %(total).1f GB for 2 trees x 2 halves): the network-
# neuroscience stages read the connectome itself. %(origin)s
"""


def make(name, spec):
    cfg = yaml.safe_load(config(name, spec))
    cfg['output_dir'] = 'results/richclub/%s' % name
    cfg['purge_connectivity'] = False
    if spec.get('revision'):
        cfg['connectivity']['revision'] = spec['revision']
    if spec.get('docs'):
        cfg['connectivity']['data_kwargs'] = {'sampling': 'documents'}
    units = spec['layers'] * spec['neurons']
    gb = units * units * 2 / 1e9
    if spec.get('source'):
        origin = ('Connectivity identical to configs/qwen35/%s.yml; its stored partitions are\n'
                  '# copied into this tree and re-scored as the reproduction check.' % spec['source'])
    elif spec.get('docs'):
        origin = ('Document-coherent text (Iteration 48): wikitext and bookcorpus as windows of\n'
                  '# contiguous text, agnews and tldr17 with the end-of-text token between documents.\n'
                  '# Full pipeline in this tree.')
    else:
        origin = 'The pilot: full pipeline in this tree.'
    return HEADER % dict(model=spec['model'], units=units, gb=gb, total=4 * gb, origin=origin) + \
        yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False)


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for name, spec in SPECS.items():
        path = os.path.join(OUT, name + '.yml')
        with open(path, 'w') as f:
            f.write(make(name, spec))
        print(os.path.relpath(path, os.path.join(HERE, '..')))
