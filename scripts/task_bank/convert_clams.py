"""CLAMS (Mueller et al. 2020) -> tier-1 number-flip counterfactual tasks. Deterministic (seed 42).

CLAMS evalsets are tab-separated (grammatical flag, sentence) with a True line followed by its False
minimal pair. CLAMS has no counterfactual prompts, so they are BUILT: for an item (prompt up to the
agreeing word(s), correct answer, incorrect answer), the counterfactual is another item of the same
file whose answers are the swapped pair and whose prompt differs only by morphological variants of the
same words (subject number swap plus words that agree with it inside the prompt); see
_syntax_pairing.py / _syntax_agreement.py. Items without a unique partner are dropped and counted.

Scope. English SVA files are NOT converted here because the English CLAMS sentence sets are identical
(case aside) to the Marvin & Linzen templates shipped by Newman et al. (source newman_sva); the three
English reflexive files are converted (reflexive number agreement). English NPI files do not fit tier 1
(the contrast is in the prompt, the continuation is shared). fr/de/he/ru: all seven agreement files.
"""
import os
import sys
from collections import Counter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _syntax_common import *  # noqa
from _syntax_agreement import build_items, sample

SID = 'clams'
LANGS = {'en': 'English', 'fr': 'French', 'de': 'German', 'he': 'Hebrew', 'ru': 'Russian'}
STRUCT_FAMILY = {  # file stem -> family stem shared with the other SVA sources
    'simple_agrmt': 'sva_simple', 'vp_coord': 'sva_vp_coord', 'long_vp_coord': 'sva_long_vp_coord', 'prep_anim': 'sva_across_pp',
    'subj_rel': 'sva_across_subj_rc', 'obj_rel_across_anim': 'sva_across_obj_rc', 'obj_rel_within_anim': 'sva_within_obj_rc',
    'simple_reflexives': 'reflexive_number_simple', 'reflexives_across': 'reflexive_number_across_obj_rc',
    'reflexive_sent_comp': 'reflexive_number_sent_comp'}
JOBS = [(l, s) for l in ('fr', 'de', 'he', 'ru') for s in ('simple_agrmt', 'vp_coord', 'long_vp_coord', 'prep_anim', 'subj_rel', 'obj_rel_across_anim', 'obj_rel_within_anim')]
JOBS += [('en', s) for s in ('simple_reflexives', 'reflexives_across', 'reflexive_sent_comp')]


def read_pairs(path):
    L = [l.rstrip('\n').split('\t') for l in open(path, encoding='utf8')]
    out = []
    for k in range(0, len(L), 2):
        assert L[k][0] == 'True' and L[k + 1][0] == 'False', (path, k)
        out.append((k + 1, L[k][1].strip(), L[k + 1][1].strip()))
    return out


def main():
    man = read_manifest(SID)
    reg_tasks, names, raw_files = [], [], []
    for lang, stem in JOBS:
        path = os.path.join(raw_dir(SID), 'repo', f'{lang}_evalset', stem + '.txt')
        raw_files.append(path)
        family = STRUCT_FAMILY[stem] + ('' if lang == 'en' else '_' + lang)
        task = f'{lang}_{stem}'
        items, st = build_items(read_pairs(path), dict(task=task, family=family, language=lang, structure=stem, source_id=SID), f'{lang}_evalset/{stem}.txt', lang=lang)
        kept = sample(items)
        names.append(task)
        write_task(SID, task, kept, [it['source_item_id'] + '|' + it['corrupted_source_item_id'] for it in kept])
        reg_tasks.append(dict(
            name=task, family=family, domain='syntax', language=LANGS[lang], n_items_raw=st['n_pairs_raw'], n_items_converted=len(kept),
            pairing_stats=st, sampled_ids_file=f'tasks/{SID}/{task}.ids.txt',
            sampling_rule='all unordered counterfactual pairs; if > 2000, seed-42 sample stratified on (clean_correct, clean_incorrect)',
            adaptations=['counterfactual built by subject-number swap (partner = other item of the same file with swapped answers and morphologically close prompt words)',
                         'answer = words from first to last differing word, leading space; shared tail after the answer dropped',
                         'clean/corrupted orientation of each pair chosen by seed-42 coin'],
            **diagnostics(kept)))
        print(task, st, len(kept), flush=True)
    write_config(SID, names)
    write_registry(SID, dict(
        source_id=SID, title='CLAMS: Cross-Linguistic Assessment of Models on Syntax',
        bibkey='mueller-etal-2020-cross', url='https://github.com/aaronmueller/clams', revision=dict(github_commit=man['github_commit']),
        download_date=man['download_date'], raw_files=[dict(path=os.path.relpath(f, TB), sha256=sha256(f)) for f in raw_files],
        licence='Apache-2.0', licence_source='external/task_bank/raw/clams/repo/LICENSE', redistribute='yes (Apache-2.0: keep licence and notice)',
        generator=dict(note='evalsets as released in the repo (generated by the authors with generator.py from the attribute-varying grammars); not regenerated here'),
        tier=1, tasks=reg_tasks, status='converted',
        notes='Counterfactuals are built by this task bank, not provided by CLAMS. English SVA files not converted (identical to Newman et al. ML templates, source newman_sva); English NPI files not fitting tier 1. Hebrew text is in the CLAMS preprocessed form (clitics split off by spaces).'))


if __name__ == '__main__':
    main()
