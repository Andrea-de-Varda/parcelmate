"""Write the task-bank evaluation lists: every converted (source, task) pair minus the exclusions below.

    python scripts/task_bank/make_eval_list.py

eval_tasks.txt holds the original tasks (for any model). eval_tasks_qwen35.txt is the list for
Qwen3.5 models: every original that has a length-matched `<task>__qwen35` variant
(repair_qwen35_*.py) is replaced by that variant. Variants never appear in eval_tasks.txt.

Exclusions are curation decisions (Andrea, 2026-10-12; info/TASK_BANK.md); everything else in
configs/ is evaluated.
"""
import glob, json, os

TB = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'external', 'task_bank')

EXCLUDE = {
    # hobby repository, no paper; tiny tasks that add nothing other sources lack
    'gpt2_syntax_circuits/*': 'dropped (hobby repo, 106 and 24 items)',
    # unmatched verb pairs; the _matched versions keep all 600 items
    'causalgym/agr_sv_num_pp': 'replaced by agr_sv_num_pp_matched',
    'causalgym/agr_sv_num_subj-relc': 'replaced by agr_sv_num_subj-relc_matched',
    'causalgym/agr_sv_num_obj-relc': 'replaced by agr_sv_num_obj-relc_matched',
    # the paper's own data replace the public-generator conversion for these formats
    'devarda_arithmetic/numeric': 'replaced by devarda_paper_arithmetic/numeric',
    'devarda_arithmetic/english': 'replaced by devarda_paper_arithmetic/english',
    'devarda_arithmetic/spanish': 'replaced by devarda_paper_arithmetic/spanish',
    'devarda_arithmetic/italian': 'replaced by devarda_paper_arithmetic/italian',
}


def excluded(source, task):
    return EXCLUDE.get('%s/%s' % (source, task)) or EXCLUDE.get('%s/*' % source)


def write(name, lines, n_ex):
    with open(os.path.join(TB, name), 'w') as f:
        f.write('# Generated by scripts/task_bank/make_eval_list.py; do not edit by hand.\n')
        f.write('\n'.join(lines) + '\n')
    print('%s: %d tasks to evaluate, %d excluded or replaced' % (name, len(lines) - n_ex, n_ex))


def main():
    lines, qlines, n_ex, n_qex = [], [], 0, 0
    for path in sorted(glob.glob(os.path.join(TB, 'configs', '*.json'))):
        source = os.path.basename(path)[:-5]
        config = json.load(open(path))
        for task, cfg in config.items():
            assert os.path.exists(os.path.join(TB, 'tasks', source, cfg['path'])), (source, task)
            if task.endswith('__qwen35'):
                continue
            why = excluded(source, task)
            if why:
                for out in (lines, qlines):
                    out.append('# %s/%s  -- %s' % (source, task, why))
                n_ex += 1
                n_qex += 1
                continue
            lines.append('%s/%s' % (source, task))
            if task + '__qwen35' in config:
                qlines.append('# %s/%s  -- replaced by its length-matched variant' % (source, task))
                qlines.append('%s/%s__qwen35' % (source, task))
                n_qex += 1
            else:
                qlines.append('%s/%s' % (source, task))
    write('eval_tasks.txt', lines, n_ex)
    write('eval_tasks_qwen35.txt', qlines, n_qex)


if __name__ == '__main__':
    main()
